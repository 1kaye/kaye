#!/usr/bin/env bash
set -euo pipefail

KAYE_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
export KAYE_PATH="$KAYE_DIR"

# shellcheck source=install/lib/logging.sh
source "$KAYE_DIR/install/lib/logging.sh"

copy_if_missing() {
  local src="$1" dst="$2"
  mkdir -p "$(dirname "$dst")"
  if [[ ! -e "$dst" ]]; then
    cp -a "$src" "$dst"
    echo "    created $dst"
  else
    echo "    kept existing $dst"
  fi
}

kaye_backup_path() {
  local target="$1"
  local backup="${target}.pre-kaye.bak"
  if [[ -e "$backup" ]]; then
    backup="${target}.pre-kaye.$(date +%s).bak"
  fi
  printf '%s\n' "$backup"
}

kaye_is_autogenerated_hypr_config() {
  local file="$1"
  [[ -f "$file" ]] || return 1
  grep -Eiq \
    'autogenerated[[:space:]]*=[[:space:]]*(true|1)|-- This is an example Hyprland Lua config file|AUTOGENERATED HYPRLAND CONFIG|using an autogenerated config' \
    "$file"
}

kaye_install_hypr_entrypoint() {
  local src_lua="$1"
  local hypr_dir="$2"
  local dst_lua="$hypr_dir/hyprland.lua"
  local legacy_conf="$hypr_dir/hyprland.conf"

  mkdir -p "$hypr_dir"

  # Replace missing or autogenerated hyprland.lua; keep genuine user-edited configs untouched.
  if [[ ! -e "$dst_lua" ]]; then
    cp -a "$src_lua" "$dst_lua"
    echo "    created $dst_lua"
  elif kaye_is_autogenerated_hypr_config "$dst_lua"; then
    local backup
    backup="$(kaye_backup_path "$dst_lua")"
    mv "$dst_lua" "$backup"
    cp -a "$src_lua" "$dst_lua"
    echo "    backed up autogenerated hyprland.lua -> $backup and installed Kaye entrypoint"
  else
    echo "    kept existing user $dst_lua"
  fi

  # Move aside stale autogenerated or legacy Kaye hyprland.conf (Hyprland 0.57+ is Lua-only).
  if [[ -f "$legacy_conf" ]]; then
    if kaye_is_autogenerated_hypr_config "$legacy_conf" || grep -q '^# Kaye OS — User Entrypoint' "$legacy_conf"; then
      local conf_backup
      conf_backup="$(kaye_backup_path "$legacy_conf")"
      mv "$legacy_conf" "$conf_backup"
      echo "    archived obsolete $legacy_conf -> $conf_backup"
    fi
  fi
}

kaye_patch_user_paths() {
  local config_root="$1"
  local kaye_dir="$2"

  if [[ -f "$config_root/hypr/hyprland.lua" ]]; then
    sed -i "s|^local default_kaye_path = .*|local default_kaye_path = \"$kaye_dir\"|" "$config_root/hypr/hyprland.lua"
  fi
  if [[ -f "$config_root/uwsm/env.d/10-kaye.conf" ]]; then
    sed -i "s|^export KAYE_PATH=.*|export KAYE_PATH=\"$kaye_dir\"|" "$config_root/uwsm/env.d/10-kaye.conf"
  fi
  if [[ -f "$config_root/systemd/user/kaye-shell.service" ]]; then
    sed -i "s|^Environment=KAYE_PATH=.*|Environment=KAYE_PATH=$kaye_dir|" "$config_root/systemd/user/kaye-shell.service"
    sed -i "s|^ExecStart=/usr/bin/quickshell -p .*|ExecStart=/usr/bin/quickshell -p $kaye_dir/shell|" "$config_root/systemd/user/kaye-shell.service"
  fi
}

kaye_enable_shell_user_unit() {
  local config_root="$1"
  local wants_dir="$config_root/systemd/user/graphical-session.target.wants"

  # Chroot-safe: always wire the graphical-session.target.wants symlink directly.
  mkdir -p "$wants_dir"
  ln -sfn ../kaye-shell.service "$wants_dir/kaye-shell.service"

  # Refresh live user manager if available (never fails in chroot or headless TTY).
  if ! kaye_is_chroot && command -v systemctl >/dev/null 2>&1; then
    if systemctl --user daemon-reload 2>/dev/null; then
      systemctl --user enable kaye-shell.service 2>/dev/null || true
    fi
  fi
}

# Allow sourcing helper functions in isolated tests without modifying the host.
if [[ "${KAYE_DOTFILES_LIB_ONLY:-0}" == "1" ]]; then
  return 0 2>/dev/null || exit 0
fi

kaye_enable_err_trap
kaye_is_chroot || true

echo "==> Building and installing Rust 'kaye' CLI binary..."
[[ -d "$HOME/.cargo/bin" ]] && export PATH="$HOME/.cargo/bin:$PATH"
mkdir -p "$HOME/.local/bin"
cargo install --path "$KAYE_DIR/core" --root "$HOME/.local" --force

echo "==> Installing system login-shell profile (/etc/profile.d/kaye.sh)..."
sudo install -d -m 755 /etc/profile.d
sudo tee /etc/profile.d/kaye.sh >/dev/null <<'EOF'
# Kaye OS — Login shell defaults
if [ -z "${KAYE_PATH:-}" ] && [ -d "$HOME/kaye" ]; then
  export KAYE_PATH="$HOME/kaye"
fi
if [ -d "$HOME/.local/bin" ]; then
  case ":$PATH:" in
    *":$HOME/.local/bin:"*) ;;
    *) export PATH="$HOME/.local/bin:$PATH" ;;
  esac
fi
EOF
sudo chmod 644 /etc/profile.d/kaye.sh

echo "==> Installing starter configs into ~/.config..."
kaye_install_hypr_entrypoint "$KAYE_DIR/config/hypr/hyprland.lua" "$HOME/.config/hypr"

for rel in \
  hypr/monitors.lua \
  hypr/input.lua \
  hypr/bindings.lua \
  hypr/looknfeel.lua \
  hypr/autostart.lua \
  hypr/.luarc.json \
  kaye/shell.json \
  kaye/menu.jsonc \
  uwsm/env.d/10-kaye.conf \
  foot/foot.ini \
  fastfetch/config.jsonc \
  systemd/user/kaye-shell.service; do
  copy_if_missing "$KAYE_DIR/config/$rel" "$HOME/.config/$rel"
done

# Point KAYE_PATH in user configs to actual clone directory.
kaye_patch_user_paths "$HOME/.config" "$KAYE_DIR"

# Copy branding files for fastfetch & shell.
mkdir -p "$HOME/.config/kaye/branding" "$HOME/.local/state/kaye/toggles"
cp -a "$KAYE_DIR/branding/." "$HOME/.config/kaye/branding/"

# Ensure ~/.bashrc exports KAYE_PATH and deduplicated ~/.local/bin.
touch "$HOME/.bashrc"
if grep -q '^export KAYE_PATH=' "$HOME/.bashrc"; then
  sed -i "s|^export KAYE_PATH=.*|export KAYE_PATH=\"$KAYE_DIR\"|" "$HOME/.bashrc"
else
  cat >>"$HOME/.bashrc" <<EOF

# Kaye OS
export KAYE_PATH="$KAYE_DIR"
case ":\$PATH:" in
  *":\$HOME/.local/bin:"*) ;;
  *) export PATH="\$HOME/.local/bin:\$PATH" ;;
esac
EOF
fi

echo "==> Enabling kaye-shell.service user unit (chroot-safe)..."
kaye_enable_shell_user_unit "$HOME/.config"
